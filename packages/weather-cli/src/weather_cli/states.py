STATE_CODES = {name.lower(): code for code, name in STATE_NAMES.items()}


def resolve_state(value: str) -> tuple[str, str] | None:
    cleaned = value.strip()
    if not cleaned:
        return None
    code = cleaned.upper()
    if code in STATE_NAMES:
        return code, STATE_NAMES[code]
    normalized = " ".join(part for part in cleaned.lower().split())
    code = STATE_CODES.get(normalized)
    if code:
        return code, STATE_NAMES[code]
    return None
